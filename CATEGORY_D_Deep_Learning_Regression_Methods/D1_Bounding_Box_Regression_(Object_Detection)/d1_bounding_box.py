# SECTION 6 — NON-MAX SUPPRESSION (hand-written)
# ============================================================================

def mine_hard_negatives(net, anchors, bg_image, img_size=128,
                        conf_threshold=0.5, max_negatives=60):
    """
    HARD NEGATIVE MINING.

    Run the current network over a real background-only image (no
    target object present -- e.g. a photo of just your table/wood
    surface). Any anchor the network classifies as "object" here is,
    by definition, a FALSE POSITIVE. Collect these as explicit hard
    negative examples and feed them back into training.

    This is the classical fix (pre-dating deep learning, used in
    Viola-Jones and HOG+SVM detectors) for a classifier that has
    learned a spurious signal -- exactly what happened here, where
    edge density from wood grain was mistaken for "object present."
    """
    resized = cv2.resize(bg_image, (img_size, img_size))
    X = np.stack([extract_features(resized, a) for a in anchors])
    cls_prob, _, _ = net.forward(X)
    cls_prob = cls_prob.flatten()

    false_pos_idx = np.where(cls_prob >= conf_threshold)[0]
    print(f"  Hard negatives found in background image: {len(false_pos_idx)}")

    if len(false_pos_idx) > max_negatives:
        false_pos_idx = np.random.choice(false_pos_idx, max_negatives,
                                         replace=False)

    hard_neg_anchors = anchors[false_pos_idx]
    if len(hard_neg_anchors) == 0:
        return np.zeros((0, 10), dtype=np.float32)
    hard_neg_features = np.stack(
        [extract_features(resized, a) for a in hard_neg_anchors])
    return hard_neg_features


def train_with_hard_negatives(net, anchors, hard_neg_features,
                              epochs=20, lr=0.02):
    """
    Fine-tune the network using ONLY hard negative examples --
    explicitly pushing their objectness score toward 0. This directly
    corrects the false-positive behaviour without needing new
    positive examples.
    """
    if len(hard_neg_features) == 0:
        print("  No hard negatives to train on -- skipping.")
        return net

    net.lr = lr
    print(f"\n  Fine-tuning on {len(hard_neg_features)} hard negatives "
          f"for {epochs} epochs...")

    cls_target = np.zeros((len(hard_neg_features), 1), dtype=np.float32)
    box_target = np.zeros((len(hard_neg_features), 4), dtype=np.float32)
    is_positive = np.zeros(len(hard_neg_features), dtype=bool)

    for epoch in range(epochs):
        cls_prob, box_pred, cache = net.forward(hard_neg_features)
        loss, cls_l, box_l = net.compute_loss(
            cls_prob, cls_target, box_pred, box_target, is_positive)
        net.backward(cache, cls_prob, cls_target, box_pred,
                     box_target, is_positive)
        if (epoch+1) % 5 == 0:
            print(f"    Epoch {epoch+1}/{epochs}  hard-neg loss={loss:.4f}  "
                  f"mean confidence now={cls_prob.mean():.4f}")

    print("  Hard negative fine-tuning complete.")
    return net


def non_max_suppression(boxes, scores, iou_threshold=0.4):
    """Standard NMS, implemented from scratch. Returns indices to keep."""
    if len(boxes) == 0:
        return []
    order = np.argsort(scores)[::-1]
    keep = []
    while len(order) > 0:
        i = order[0]
        keep.append(i)
        if len(order) == 1:
            break
        rest = order[1:]
        ious = box_iou(boxes[i:i+1], boxes[rest]).flatten()
        order = rest[ious < iou_threshold]
    return keep


def propose_regions_by_contour(image, min_area_frac=0.01, max_area_frac=0.5):
    """
    CLASSICAL region proposal (like the original R-CNN, before Faster
    R-CNN added a learned RPN). Instead of blindly classifying a dense
    grid of thousands of anchors everywhere, use classical segmentation
    to find the small number of regions that actually LOOK like a
    distinct object -- then only classify those.

    This directly fixes the false-positive-everywhere failure: there
    is no dense grid left for a weak classifier to misfire on.
    """
    h, w = image.shape[:2]
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
    blur = cv2.GaussianBlur(gray, (5,5), 0)

    # Otsu automatic thresholding -- try both polarities, keep whichever
    # produces sane-looking connected components
    _, th1 = cv2.threshold(blur, 0, 255, cv2.THRESH_BINARY+cv2.THRESH_OTSU)
    _, th2 = cv2.threshold(blur, 0, 255, cv2.THRESH_BINARY_INV+cv2.THRESH_OTSU)

    proposals = []
    for th in (th1, th2):
        kernel = np.ones((5,5), np.uint8)
        clean = cv2.morphologyEx(th, cv2.MORPH_CLOSE, kernel, iterations=2)
        clean = cv2.morphologyEx(clean, cv2.MORPH_OPEN, kernel, iterations=1)

        contours, _ = cv2.findContours(clean, cv2.RETR_EXTERNAL,
                                        cv2.CHAIN_APPROX_SIMPLE)
        img_area = h * w
        for c in contours:
            area = cv2.contourArea(c)
            frac = area / img_area
            if min_area_frac <= frac <= max_area_frac:
                x,y,bw,bh = cv2.boundingRect(c)
                # Reject boxes touching image border (likely surface/shadow)
                margin = 3
                if x<margin or y<margin or x+bw>w-margin or y+bh>h-margin:
                    continue
                proposals.append([x, y, x+bw, y+bh])

    if not proposals:
        return np.zeros((0,4), dtype=np.float32)

    proposals = np.array(proposals, dtype=np.float32)
    # De-duplicate near-identical proposals from the two threshold polarities
    keep = non_max_suppression(proposals, np.ones(len(proposals)), 0.6)
    return proposals[keep]


def detect_and_measure_hybrid(net, image, scale_cm_per_px,
                              conf_threshold=0.5):
    """
    HYBRID pipeline: classical contour proposals (few, precise) +
    learned classifier/regressor (scores and refines each proposal).

    Use this instead of detect_and_measure() for single/few-object
    scenes -- it is far more robust than dense anchor sliding-window
    search with a weak hand-crafted-feature classifier.
    """
    proposals = propose_regions_by_contour(image)
    print(f"  Contour-based candidate regions found: {len(proposals)}")

    if len(proposals) == 0:
        return image.copy(), pd.DataFrame(
            columns=["x1","y1","x2","y2","width_px","height_px",
                     "width_cm","height_cm","area_cm2","confidence"])

    X = np.stack([extract_features(image, box) for box in proposals])
    cls_prob, box_pred, _ = net.forward(X)
    cls_prob = cls_prob.flatten()

    print(f"  Candidate confidences: "
          f"{[f'{s:.2f}' for s in sorted(cls_prob, reverse=True)]}")

    keep_mask = cls_prob >= conf_threshold
    if keep_mask.sum() == 0:
        print(f"  No candidates above confidence {conf_threshold}. "
              f"Showing all candidates with raw scores instead.")
        keep_mask = np.ones(len(proposals), dtype=bool)

    final_boxes  = proposals[keep_mask]
    final_scores = cls_prob[keep_mask]

    vis = image.copy()
    rows = []
    for box, score in zip(final_boxes, final_scores):
        x1,y1,x2,y2 = box
        w_px, h_px = x2-x1, y2-y1
        w_cm, h_cm = w_px*scale_cm_per_px, h_px*scale_cm_per_px

        cv2.rectangle(vis, (int(x1),int(y1)), (int(x2),int(y2)), (0,200,80), 2)
        put_text(vis, f"{score:.2f} | {w_cm:.1f}x{h_cm:.1f}cm",
                 (int(x1), int(max(15,y1-8))), (0,200,80), 0.5)

        rows.append({
            "x1":x1,"y1":y1,"x2":x2,"y2":y2,
            "width_px":w_px, "height_px":h_px,
            "width_cm":w_cm, "height_cm":h_cm,
            "area_cm2":w_cm*h_cm, "confidence":score
        })

    return vis, pd.DataFrame(rows)


def propose_regions_two_stage(image, min_area_frac=0.001, max_area_frac=0.3):
    """
    TWO-STAGE region proposal, built for the real use case: an object
    placed ON a reference surface (A4 paper, cutting board, etc.)
    which itself sits on a textured background (wood table).

    A single global threshold fails here because the object is a
    *hole* inside the paper's contour, invisible to RETR_EXTERNAL.

    Stage 1: find the paper/reference region (large, bright, roughly
             rectangular blob against the background)
    Stage 2: search ONLY inside that region for the object (which is
             darker/different from the paper it sits on)

    This mirrors exactly how you will use the pipeline in practice --
    object always placed on a known reference sheet.
    """
    h, w = image.shape[:2]
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
    blur = cv2.GaussianBlur(gray, (5,5), 0)

    # ---- Stage 1: find the paper/reference region ----
    _, bright_mask = cv2.threshold(blur, 0, 255,
                                    cv2.THRESH_BINARY+cv2.THRESH_OTSU)
    kernel = np.ones((9,9), np.uint8)
    bright_clean = cv2.morphologyEx(bright_mask, cv2.MORPH_CLOSE, kernel, 2)
    contours, _ = cv2.findContours(bright_clean, cv2.RETR_EXTERNAL,
                                    cv2.CHAIN_APPROX_SIMPLE)

    if not contours:
        return np.zeros((0,4), dtype=np.float32), None

    paper_contour = max(contours, key=cv2.contourArea)
    px, py, pw, ph = cv2.boundingRect(paper_contour)
    paper_box = np.array([px, py, px+pw, py+ph], dtype=np.float32)

    # Reject if "paper" region is basically the whole image (bad threshold)
    if (pw*ph) / (w*h) > 0.85:
        paper_box = None

    # ---- Stage 2: search for object INSIDE the paper region ----
    if paper_box is not None:
        pad = 5
        rx1 = max(0, px+pad); ry1 = max(0, py+pad)
        rx2 = min(w, px+pw-pad); ry2 = min(h, py+ph-pad)
        roi = image[ry1:ry2, rx1:rx2]
    else:
        rx1, ry1 = 0, 0
        roi = image

    if roi.size == 0:
        return np.zeros((0,4), dtype=np.float32), paper_box

    roi_gray = cv2.cvtColor(roi, cv2.COLOR_BGR2GRAY)
    roi_blur = cv2.GaussianBlur(roi_gray, (5,5), 0)
    # Object should be darker than the (bright) paper it sits on
    _, obj_mask = cv2.threshold(roi_blur, 0, 255,
                                 cv2.THRESH_BINARY_INV+cv2.THRESH_OTSU)
    kernel2 = np.ones((5,5), np.uint8)
    obj_clean = cv2.morphologyEx(obj_mask, cv2.MORPH_CLOSE, kernel2, 2)
    obj_clean = cv2.morphologyEx(obj_clean, cv2.MORPH_OPEN, kernel2, 1)

    obj_contours, _ = cv2.findContours(obj_clean, cv2.RETR_EXTERNAL,
                                        cv2.CHAIN_APPROX_SIMPLE)

    roi_area = roi.shape[0]*roi.shape[1]
    proposals = []
    for c in obj_contours:
        area = cv2.contourArea(c)
        frac = area / roi_area
        if min_area_frac <= frac <= max_area_frac:
            ox,oy,ow,oh = cv2.boundingRect(c)
            proposals.append([rx1+ox, ry1+oy, rx1+ox+ow, ry1+oy+oh])

    proposals = np.array(proposals) if proposals else np.zeros((0,4))
    if len(proposals) > 0:
        keep = non_max_suppression(proposals, np.ones(len(proposals)), 0.5)
        proposals_inside = proposals[keep]
    else:
        proposals_inside = np.zeros((0,4), dtype=np.float32)

    # ---- Stage 3: ALSO search OUTSIDE the paper (object may sit on
    #      the background surface, separate from the reference sheet).
    #      Search four independent strips (top/bottom/left/right of the
    #      paper) rather than masking the whole image -- masking with
    #      zeros corrupts Otsu's histogram statistics badly. ----
    proposals_outside = np.zeros((0,4), dtype=np.float32)
    if paper_box is not None:
        strips = []
        if py > 10:
            strips.append((0, 0, w, py))               # top strip
        if py+ph < h-10:
            strips.append((0, py+ph, w, h))             # bottom strip
        if px > 10:
            strips.append((0, 0, px, h))                # left strip
        if px+pw < w-10:
            strips.append((px+pw, 0, w, h))              # right strip

        out_props = []
        for (sx1, sy1, sx2, sy2) in strips:
            strip = image[sy1:sy2, sx1:sx2]
            if strip.size == 0:
                continue
            s_gray = cv2.cvtColor(strip, cv2.COLOR_BGR2GRAY)
            s_blur = cv2.GaussianBlur(s_gray, (5,5), 0)
            for mode in (cv2.THRESH_BINARY, cv2.THRESH_BINARY_INV):
                _, th = cv2.threshold(s_blur, 0, 255, mode+cv2.THRESH_OTSU)
                k = np.ones((7,7), np.uint8)
                clean = cv2.morphologyEx(th, cv2.MORPH_CLOSE, k, 2)
                clean = cv2.morphologyEx(clean, cv2.MORPH_OPEN, k, 1)
                cnts, _ = cv2.findContours(clean, cv2.RETR_EXTERNAL,
                                            cv2.CHAIN_APPROX_SIMPLE)
                strip_area = strip.shape[0]*strip.shape[1]
                for c in cnts:
                    area = cv2.contourArea(c)
                    frac = area / strip_area
                    if 0.01 <= frac <= 0.5:
                        x,y,bw,bh = cv2.boundingRect(c)
                        margin = 3
                        sh_, sw_ = strip.shape[:2]
                        if x<margin or y<margin or x+bw>sw_-margin or y+bh>sh_-margin:
                            continue
                        out_props.append([sx1+x, sy1+y, sx1+x+bw, sy1+y+bh])

        if out_props:
            out_props = np.array(out_props, dtype=np.float32)
            keep2 = non_max_suppression(out_props, np.ones(len(out_props)), 0.5)
            proposals_outside = out_props[keep2]

    all_proposals = np.concatenate([proposals_inside, proposals_outside], axis=0) \
                     if len(proposals_outside) > 0 else proposals_inside

    if len(all_proposals) == 0:
        return np.zeros((0,4), dtype=np.float32), paper_box
    return all_proposals, paper_box



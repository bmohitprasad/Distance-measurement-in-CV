def detect_and_measure(net, anchors, image, scale_cm_per_px,
                        conf_threshold=0.6, nms_iou=0.4,
                        train_img_size=128):
    """
    Run trained network over a real image using a sliding-anchor grid
    resized to match training scale, then decode + NMS + convert to cm.
    """
    h, w = image.shape[:2]
    resized = cv2.resize(image, (train_img_size, train_img_size))

    # Feature + forward pass for every anchor
    X = np.stack([extract_features(resized, a) for a in anchors])
    cls_prob, box_pred, _ = net.forward(X)
    cls_prob = cls_prob.flatten()

    keep_mask = cls_prob >= conf_threshold
    print(f"  Anchors above confidence {conf_threshold}: {keep_mask.sum()} / {len(anchors)}")

    if keep_mask.sum() == 0:
        return image.copy(), pd.DataFrame(
            columns=["x1","y1","x2","y2","width_px","height_px",
                     "width_cm","height_cm","area_cm2","confidence"])

    kept_anchors = anchors[keep_mask]
    kept_offsets = box_pred[keep_mask]
    kept_scores  = cls_prob[keep_mask]

    decoded_boxes = np.stack([
        decode_box(a, o) for a, o in zip(kept_anchors, kept_offsets)
    ])
    # Clip to training-image bounds
    decoded_boxes[:,[0,2]] = np.clip(decoded_boxes[:,[0,2]], 0, train_img_size)
    decoded_boxes[:,[1,3]] = np.clip(decoded_boxes[:,[1,3]], 0, train_img_size)

    keep_idx = non_max_suppression(decoded_boxes, kept_scores, nms_iou)
    final_boxes  = decoded_boxes[keep_idx]
    final_scores = kept_scores[keep_idx]

    # Scale boxes back to original image resolution
    sx, sy = w/train_img_size, h/train_img_size
    final_boxes[:,[0,2]] *= sx
    final_boxes[:,[1,3]] *= sy

    vis = image.copy()
    rows = []
    for box, score in zip(final_boxes, final_scores):
        x1,y1,x2,y2 = box
        w_px, h_px = x2-x1, y2-y1
        w_cm, h_cm = w_px*scale_cm_per_px, h_px*scale_cm_per_px
        area_cm2 = w_cm*h_cm

        cv2.rectangle(vis, (int(x1),int(y1)), (int(x2),int(y2)), (0,200,80), 2)
        put_text(vis, f"{score:.2f} | {w_cm:.1f}x{h_cm:.1f}cm",
                 (int(x1), int(max(15,y1-8))), (0,200,80), 0.5)

        rows.append({
            "x1":x1,"y1":y1,"x2":x2,"y2":y2,
            "width_px":w_px, "height_px":h_px,
            "width_cm":w_cm, "height_cm":h_cm,
            "area_cm2":area_cm2, "confidence":score
        })

    df = pd.DataFrame(rows)
    return vis, df



"""
METHOD D1 (FROM SCRATCH) — Bounding Box Regression, No Pretrained Models
===========================================================================
CONSTRAINT: Only numpy, opencv, pandas. No torch/sklearn/pretrained weights.

WHAT THIS BUILDS, FROM ZERO:
    1. Anchor boxes         - generated by sliding a grid over the image
    2. Feature extraction   - hand-computed pixel statistics per anchor
                               (mean intensity, std dev, edge density via
                               Sobel, aspect ratio) -- NOT a pretrained CNN
    3. A neural network     - written with raw numpy: forward pass,
                               backward pass, gradient descent, ALL
                               derived and coded by hand (no autograd)
    4. Two loss functions   - Binary Cross-Entropy (objectness: is there
                               an object in this anchor?) and Smooth L1
                               (box regression: how to adjust the anchor
                               to fit the object)
    5. Non-Max Suppression  - written by hand, removes duplicate boxes
    6. Training data         - generated synthetically (random rectangles
                               on random backgrounds) since we have no
                               pretrained model and no labelled dataset
    7. cm conversion         - same scale-factor principle as every
                               other method in this project

WHY SYNTHETIC TRAINING DATA:
    A neural network needs labelled examples to learn "adjust this anchor
    by this much." With zero pretrained weights and zero external
    datasets allowed, the only way to train is to generate our own
    labelled data. This script draws random rectangles (simulating
    objects) at random positions/sizes on random backgrounds, and uses
    the KNOWN ground truth box as the training label. This lets the
    network learn genuine bounding-box regression from mathematical
    first principles.

    Once you have real labelled rice-grain images later, you swap the
    synthetic data generator for your real dataset -- the network,
    training loop, and math stay identical.

HOW TO RUN:
    # Train from scratch on synthetic data, then test on a real image:
    python method_d1_scratch.py --train --image your_photo.jpg --scale 0.05

    # Just run the synthetic demo end-to-end (train + test on synthetic):
    python method_d1_scratch.py --demo

    # Use a previously trained model (skips retraining):
    python method_d1_scratch.py --image your_photo.jpg --scale 0.05 \
        --load_weights weights.npz

    # Interactive reference scale + real image:
    python method_d1_scratch.py --image your_photo.jpg \
        --interactive_ref --ref_cm 21.0
"""

import cv2
import numpy as np
import pandas as pd
import argparse
import os
import math

np.random.seed(42)

# ============================================================================
# SECTION 1 — SYNTHETIC TRAINING DATA GENERATION
# ============================================================================

def make_textured_background(img_size):
    """
    Generate a wood-grain-like textured background: directional noise
    stripes. Real surfaces (wood, fabric, tile) have HIGH edge density
    everywhere -- the network must learn that edges alone don't mean
    'object'; only edges forming a coherent blob distinct from
    surrounding texture do.
    """
    base = np.random.randint(90, 180)
    img = np.full((img_size, img_size, 3), base, dtype=np.uint8)
    # Horizontal or vertical grain stripes
    vertical = np.random.rand() < 0.5
    n_stripes = np.random.randint(15, 40)
    for _ in range(n_stripes):
        pos = np.random.randint(0, img_size)
        thickness = np.random.randint(1, 4)
        shade = np.random.randint(-40, 40)
        color = np.clip(base + shade, 0, 255)
        if vertical:
            img[:, pos:pos+thickness] = color
        else:
            img[pos:pos+thickness, :] = color
    # Slight blur so stripes look organic, not hard-edged
    img = cv2.GaussianBlur(img, (3,3), 0)
    # Tint toward brown (wood-like) sometimes
    if np.random.rand() < 0.6:
        img = img.astype(np.int16)
        img[:,:,0] = np.clip(img[:,:,0]*0.6, 0, 255)   # less blue
        img[:,:,1] = np.clip(img[:,:,1]*0.8, 0, 255)   # less green
        img = img.astype(np.uint8)
    noise = np.random.randint(-8,8,img.shape,dtype=np.int16)
    img = np.clip(img.astype(np.int16)+noise,0,255).astype(np.uint8)
    return img


def generate_synthetic_sample(img_size=128, textured_bg_prob=0.7):
    """
    Create one synthetic training image: a random-colored rectangle
    (the 'object') on a background that is EITHER flat-color OR
    textured (wood-grain-like), so the classifier learns to
    distinguish real objects from textured surfaces. Returns the
    image and the ground-truth box [x1,y1,x2,y2].
    """
    if np.random.rand() < textured_bg_prob:
        img = make_textured_background(img_size)
    else:
        bg_color = np.random.randint(150, 230, 3).tolist()
        img = np.full((img_size, img_size, 3), bg_color, dtype=np.uint8)

    # Random object box (width/height between 20% and 60% of image)
    w = np.random.randint(int(0.2*img_size), int(0.6*img_size))
    h = np.random.randint(int(0.2*img_size), int(0.6*img_size))
    x1 = np.random.randint(0, img_size - w)
    y1 = np.random.randint(0, img_size - h)
    x2, y2 = x1 + w, y1 + h

    obj_color = np.random.randint(20, 120, 3).tolist()
    shape = np.random.choice(['rect', 'ellipse'])
    if shape == 'rect':
        cv2.rectangle(img, (x1,y1), (x2,y2), obj_color, -1)
    else:
        cv2.ellipse(img, ((x1+x2)//2,(y1+y2)//2), (w//2,h//2),
                    0, 0, 360, obj_color, -1)

    # Add noise so features aren't trivially separable
    noise = np.random.randint(-10, 10, img.shape, dtype=np.int16)
    img = np.clip(img.astype(np.int16) + noise, 0, 255).astype(np.uint8)

    return img, np.array([x1, y1, x2, y2], dtype=np.float32)


def generate_dataset(n_samples=400, img_size=128):
    """Generate n synthetic (image, box) training pairs."""
    images, boxes = [], []
    for _ in range(n_samples):
        img, box = generate_synthetic_sample(img_size)
        images.append(img)
        boxes.append(box)
    return images, boxes


# ============================================================================
# SECTION 2 — ANCHOR BOXES (hand-built, no library)
# ============================================================================

def generate_anchors(img_size, stride=16, scales=(32,64), ratios=(0.5,1.0,2.0)):
    """
    Slide a grid of anchor boxes over the image.

    stride  : spacing between anchor centers (pixels)
    scales  : anchor box areas (as side length in px, roughly)
    ratios  : width:height ratios per scale

    Returns: (N,4) array of anchor boxes [x1,y1,x2,y2]
    """
    anchors = []
    for cy in range(stride//2, img_size, stride):
        for cx in range(stride//2, img_size, stride):
            for s in scales:
                for r in ratios:
                    w = s * math.sqrt(r)
                    h = s / math.sqrt(r)
                    x1 = cx - w/2
                    y1 = cy - h/2
                    x2 = cx + w/2
                    y2 = cy + h/2
                    anchors.append([x1,y1,x2,y2])
    anchors = np.array(anchors, dtype=np.float32)
    # Clip to image bounds
    anchors[:,0] = np.clip(anchors[:,0], 0, img_size-1)
    anchors[:,1] = np.clip(anchors[:,1], 0, img_size-1)
    anchors[:,2] = np.clip(anchors[:,2], 0, img_size-1)
    anchors[:,3] = np.clip(anchors[:,3], 0, img_size-1)
    return anchors


def box_iou(boxes1, boxes2):
    """
    Vectorized IoU between two sets of boxes.
    boxes1: (N,4)  boxes2: (M,4)  -> returns (N,M) IoU matrix
    """
    N, M = len(boxes1), len(boxes2)
    iou = np.zeros((N, M), dtype=np.float32)
    for i in range(N):
        x1 = np.maximum(boxes1[i,0], boxes2[:,0])
        y1 = np.maximum(boxes1[i,1], boxes2[:,1])
        x2 = np.minimum(boxes1[i,2], boxes2[:,2])
        y2 = np.minimum(boxes1[i,3], boxes2[:,3])
        inter = np.maximum(0, x2-x1) * np.maximum(0, y2-y1)
        area1 = (boxes1[i,2]-boxes1[i,0]) * (boxes1[i,3]-boxes1[i,1])
        area2 = (boxes2[:,2]-boxes2[:,0]) * (boxes2[:,3]-boxes2[:,1])
        union = area1 + area2 - inter
        iou[i] = inter / (union + 1e-7)
    return iou


def encode_box_targets(anchors, gt_box):
    """
    Convert ground-truth box into regression targets (tx,ty,tw,th)
    relative to each anchor -- exactly the anchor-offset math from
    Faster R-CNN theory, derived here by hand.
    """
    ax1,ay1,ax2,ay2 = anchors[:,0],anchors[:,1],anchors[:,2],anchors[:,3]
    aw = ax2-ax1; ah = ay2-ay1
    acx = ax1 + aw/2; acy = ay1 + ah/2

    gx1,gy1,gx2,gy2 = gt_box
    gw = gx2-gx1; gh = gy2-gy1
    gcx = gx1 + gw/2; gcy = gy1 + gh/2

    tx = (gcx - acx) / (aw + 1e-7)
    ty = (gcy - acy) / (ah + 1e-7)
    tw = np.log((gw + 1e-7) / (aw + 1e-7))
    th = np.log((gh + 1e-7) / (ah + 1e-7))
    return np.stack([tx,ty,tw,th], axis=1)


def decode_box(anchor, offsets):
    """Inverse of encode_box_targets -- turn (tx,ty,tw,th) back into a box."""
    ax1,ay1,ax2,ay2 = anchor
    aw, ah = ax2-ax1, ay2-ay1
    acx, acy = ax1+aw/2, ay1+ah/2

    tx,ty,tw,th = offsets
    pcx = tx*aw + acx
    pcy = ty*ah + acy
    pw  = aw * math.exp(np.clip(tw, -4, 4))
    ph  = ah * math.exp(np.clip(th, -4, 4))

    return np.array([pcx-pw/2, pcy-ph/2, pcx+pw/2, pcy+ph/2])


# ============================================================================
# SECTION 3 — HAND-CRAFTED FEATURE EXTRACTION (no pretrained CNN)
# ============================================================================

def extract_features(image, box):
    """
    Compute a feature vector for the image region inside `box`,
    using only basic pixel statistics and OpenCV's classical (non-ML)
    operators -- Sobel gradients, standard deviation, etc.

    This replaces the "backbone CNN" of a real detector. It is far
    weaker than a learned CNN feature extractor, but it is built
    entirely from first principles as required.
    """
    h, w = image.shape[:2]
    x1,y1,x2,y2 = [int(max(0,min(v, w if i%2==0 else h)))
                   for i,v in enumerate(box)]
    x1,x2 = sorted([max(0,min(x1,w-1)), max(0,min(x2,w-1))])
    y1,y2 = sorted([max(0,min(y1,h-1)), max(0,min(y2,h-1))])
    if x2<=x1: x2 = x1+1
    if y2<=y1: y2 = y1+1

    patch = image[y1:y2, x1:x2]
    if patch.size == 0:
        return np.zeros(10, dtype=np.float32)

    gray = cv2.cvtColor(patch, cv2.COLOR_BGR2GRAY).astype(np.float32)

    mean_i  = gray.mean()
    std_i   = gray.std()

    sobel_x = cv2.Sobel(gray, cv2.CV_32F, 1, 0, ksize=3)
    sobel_y = cv2.Sobel(gray, cv2.CV_32F, 0, 1, ksize=3)
    grad_mag = np.sqrt(sobel_x**2 + sobel_y**2)
    edge_density = grad_mag.mean()
    edge_std     = grad_mag.std()

    # Color channel means (BGR)
    b_mean, g_mean, r_mean = patch[:,:,0].mean(), patch[:,:,1].mean(), patch[:,:,2].mean()

    box_w = x2-x1
    box_h = y2-y1
    aspect = box_w / (box_h + 1e-7)
    rel_area = (box_w*box_h) / (w*h)

    feat = np.array([
        mean_i/255.0, std_i/255.0,
        edge_density/255.0, edge_std/255.0,
        b_mean/255.0, g_mean/255.0, r_mean/255.0,
        aspect/5.0, rel_area,
        1.0   # bias-friendly constant feature
    ], dtype=np.float32)
    return feat



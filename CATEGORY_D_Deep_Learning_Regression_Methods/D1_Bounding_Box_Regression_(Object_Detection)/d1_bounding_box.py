def interactive_reference(image):
    pts = []
    def cb(event,x,y,flags,param):
        if event == cv2.EVENT_LBUTTONDOWN and len(pts) < 2:
            pts.append((x,y))
            print(f"  Point {len(pts)}: ({x},{y})")
    win = "Click reference length - press Q when done"
    cv2.namedWindow(win, cv2.WINDOW_NORMAL)
    cv2.imshow(win, image); cv2.waitKey(1)
    cv2.setMouseCallback(win, cb)
    while True:
        disp = image.copy()
        for p in pts: cv2.circle(disp,p,6,(0,80,220),-1)
        if len(pts)==2: cv2.line(disp,pts[0],pts[1],(0,200,80),2)
        cv2.imshow(win, disp)
        if cv2.waitKey(1)&0xFF==ord('q') or len(pts)==2: break
    cv2.destroyAllWindows()
    return math.dist(pts[0],pts[1]) if len(pts)==2 else None



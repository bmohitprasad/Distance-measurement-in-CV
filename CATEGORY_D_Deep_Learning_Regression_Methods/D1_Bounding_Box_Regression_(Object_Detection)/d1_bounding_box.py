# SECTION 5 — TRAINING LOOP
# ============================================================================

def train_network(n_samples=400, img_size=128, epochs=60, lr=0.05,
                  pos_iou_thresh=0.5, neg_iou_thresh=0.2):
    """
    Full training loop: generate synthetic data, build anchors, label
    them by IoU with ground truth, extract features, train the MLP
    with manual gradient descent.
    """
    print("\n  Generating synthetic training data...")
    images, gt_boxes = generate_dataset(n_samples, img_size)

    anchors = generate_anchors(img_size, stride=16, scales=(32,56), ratios=(0.5,1.0,2.0))
    print(f"  Anchors per image: {len(anchors)}")

    net = TinyDetectorNet(in_dim=10, h1=32, h2=16, lr=lr)

    print(f"  Training for {epochs} epochs on {n_samples} synthetic images...\n")

    for epoch in range(epochs):
        epoch_loss, epoch_cls, epoch_box = 0.0, 0.0, 0.0
        n_batches = 0

        for img, gt_box in zip(images, gt_boxes):
            ious = box_iou(anchors, gt_box.reshape(1,4)).flatten()

            is_positive = ious >= pos_iou_thresh
            is_negative = ious < neg_iou_thresh

            # Balance: sample a subset of negatives (there are far more
            # negative anchors than positive -- classic class imbalance)
            pos_idx = np.where(is_positive)[0]
            neg_idx = np.where(is_negative)[0]
            n_pos = len(pos_idx)
            n_neg = min(len(neg_idx), max(8, n_pos*3))
            if n_neg > 0:
                neg_idx = np.random.choice(neg_idx, n_neg, replace=False)

            if n_pos == 0:
                # Force the single best-IoU anchor to be positive
                best = np.argmax(ious)
                pos_idx = np.array([best])
                is_positive = np.zeros(len(anchors), dtype=bool)
                is_positive[best] = True

            sample_idx = np.concatenate([pos_idx, neg_idx]).astype(int)
            if len(sample_idx) == 0:
                continue

            sample_anchors = anchors[sample_idx]
            sample_is_pos  = is_positive[sample_idx]

            # Features per sampled anchor
            X = np.stack([extract_features(img, a) for a in sample_anchors])

            cls_target = sample_is_pos.reshape(-1,1).astype(np.float32)
            box_target = np.zeros((len(sample_idx), 4), dtype=np.float32)
            if sample_is_pos.sum() > 0:
                pos_anchors_full = sample_anchors[sample_is_pos]
                box_target[sample_is_pos] = encode_box_targets(
                    pos_anchors_full, gt_box)

            cls_prob, box_pred, cache = net.forward(X)
            loss, cls_l, box_l = net.compute_loss(
                cls_prob, cls_target, box_pred, box_target, sample_is_pos)
            net.backward(cache, cls_prob, cls_target, box_pred,
                        box_target, sample_is_pos)

            epoch_loss += loss; epoch_cls += cls_l; epoch_box += box_l
            n_batches += 1

        if (epoch+1) % 10 == 0 or epoch == 0:
            print(f"  Epoch {epoch+1:3d}/{epochs}  "
                  f"loss={epoch_loss/n_batches:.4f}  "
                  f"cls={epoch_cls/n_batches:.4f}  "
                  f"box={epoch_box/n_batches:.4f}")

    print("\n  Training complete.")
    return net, anchors



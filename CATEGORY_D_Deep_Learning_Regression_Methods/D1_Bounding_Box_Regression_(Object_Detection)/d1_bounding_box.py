# SECTION 4 — NEURAL NETWORK, FULLY FROM SCRATCH (numpy only)
# ============================================================================

class TinyDetectorNet:
    """
    Small MLP trained from scratch with manual forward/backward passes.

    Architecture:
        Input (10 features)
          -> Dense(32) + ReLU
          -> Dense(16) + ReLU
          -> TWO heads:
               objectness head -> Dense(1) + Sigmoid   (binary cls)
               box head        -> Dense(4)             (regression: tx,ty,tw,th)

    Every gradient below is derived by hand via the chain rule --
    no autograd, no external ML library.
    """

    def __init__(self, in_dim=10, h1=32, h2=16, lr=0.01):
        rng = np.random.RandomState(42)
        self.lr = lr
        # Xavier-ish init
        self.W1 = rng.randn(in_dim, h1) * math.sqrt(2.0/in_dim)
        self.b1 = np.zeros(h1)
        self.W2 = rng.randn(h1, h2) * math.sqrt(2.0/h1)
        self.b2 = np.zeros(h2)
        self.W_cls = rng.randn(h2, 1) * math.sqrt(2.0/h2)
        self.b_cls = np.zeros(1)
        self.W_box = rng.randn(h2, 4) * math.sqrt(1.0/h2)
        self.b_box = np.zeros(4)

    @staticmethod
    def relu(x):
        return np.maximum(0, x)

    @staticmethod
    def relu_grad(x):
        return (x > 0).astype(np.float32)

    @staticmethod
    def sigmoid(x):
        x = np.clip(x, -30, 30)
        return 1.0 / (1.0 + np.exp(-x))

    def forward(self, X):
        """X: (N, in_dim) -> returns cls_prob (N,1), box_pred (N,4), cache for backward"""
        z1 = X @ self.W1 + self.b1
        a1 = self.relu(z1)
        z2 = a1 @ self.W2 + self.b2
        a2 = self.relu(z2)

        cls_logit = a2 @ self.W_cls + self.b_cls
        cls_prob  = self.sigmoid(cls_logit)

        box_pred  = a2 @ self.W_box + self.b_box

        cache = (X, z1, a1, z2, a2, cls_logit)
        return cls_prob, box_pred, cache

    def compute_loss(self, cls_prob, cls_target, box_pred, box_target, is_positive):
        """
        cls_target  : (N,1) 1 if object, 0 if background
        box_target  : (N,4) regression targets, only meaningful where is_positive
        is_positive : (N,) boolean mask -- box loss only applies to positive anchors
        """
        eps = 1e-7
        # Binary cross-entropy for objectness
        bce = -(cls_target*np.log(cls_prob+eps) +
                (1-cls_target)*np.log(1-cls_prob+eps))
        cls_loss = bce.mean()

        # Smooth L1 for box regression -- ONLY on positive anchors
        diff = box_pred - box_target
        abs_diff = np.abs(diff)
        smooth = np.where(abs_diff < 1, 0.5*diff**2, abs_diff - 0.5)
        if is_positive.sum() > 0:
            box_loss = smooth[is_positive].sum() / max(1, is_positive.sum())
        else:
            box_loss = 0.0

        total = cls_loss + box_loss
        return total, cls_loss, box_loss

    def backward(self, cache, cls_prob, cls_target, box_pred, box_target, is_positive):
        X, z1, a1, z2, a2, cls_logit = cache
        N = X.shape[0]

        # ---- Gradient of BCE w.r.t. cls_logit (sigmoid+BCE combined = simple) ----
        d_cls_logit = (cls_prob - cls_target) / N            # (N,1)

        # ---- Gradient of Smooth L1 w.r.t. box_pred (masked to positives) ----
        diff = box_pred - box_target
        d_smooth = np.where(np.abs(diff) < 1, diff, np.sign(diff))
        mask = is_positive.reshape(-1,1).astype(np.float32)
        n_pos = max(1, is_positive.sum())
        d_box_pred = d_smooth * mask / n_pos                  # (N,4)

        # ---- Output layer grads ----
        dW_cls = a2.T @ d_cls_logit
        db_cls = d_cls_logit.sum(axis=0)
        dW_box = a2.T @ d_box_pred
        db_box = d_box_pred.sum(axis=0)

        # ---- Backprop into shared trunk (a2) ----
        d_a2 = d_cls_logit @ self.W_cls.T + d_box_pred @ self.W_box.T
        d_z2 = d_a2 * self.relu_grad(z2)

        dW2 = a1.T @ d_z2
        db2 = d_z2.sum(axis=0)

        d_a1 = d_z2 @ self.W2.T
        d_z1 = d_a1 * self.relu_grad(z1)

        dW1 = X.T @ d_z1
        db1 = d_z1.sum(axis=0)

        # ---- Gradient descent update ----
        self.W_cls -= self.lr * dW_cls
        self.b_cls -= self.lr * db_cls
        self.W_box -= self.lr * dW_box
        self.b_box -= self.lr * db_box
        self.W2    -= self.lr * dW2
        self.b2    -= self.lr * db2
        self.W1    -= self.lr * dW1
        self.b1    -= self.lr * db1

    def save(self, path):
        np.savez(path, W1=self.W1, b1=self.b1, W2=self.W2, b2=self.b2,
                 W_cls=self.W_cls, b_cls=self.b_cls,
                 W_box=self.W_box, b_box=self.b_box)
        print(f"  Weights saved -> {path}")

    def load(self, path):
        d = np.load(path)
        self.W1, self.b1 = d['W1'], d['b1']
        self.W2, self.b2 = d['W2'], d['b2']
        self.W_cls, self.b_cls = d['W_cls'], d['b_cls']
        self.W_box, self.b_box = d['W_box'], d['b_box']
        print(f"  Weights loaded from {path}")


